-- Pencatatan transaksi lewat bot Telegram.

-- 1. Referensi pesan Telegram di transaksi: mencegah transaksi ganda saat Telegram mengirim ulang update
ALTER TABLE transactions ADD COLUMN telegram_chat_id BIGINT;
ALTER TABLE transactions ADD COLUMN telegram_message_id BIGINT;
CREATE UNIQUE INDEX ux_transactions_telegram_message
    ON transactions (telegram_chat_id, telegram_message_id)
    WHERE telegram_chat_id IS NOT NULL;

-- 2. Kata kunci bawaan untuk menebak kategori (satu kata kunci hanya milik satu kategori)
CREATE TABLE category_keywords (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT      NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    keyword      VARCHAR(40) NOT NULL,
    CONSTRAINT ux_category_keywords_keyword UNIQUE (keyword),
    CONSTRAINT chk_category_keywords_lower CHECK (keyword = lower(keyword))
);

-- 3. Kata kunci pribadi hasil koreksi user (dicek lebih dulu daripada kata kunci bawaan)
CREATE TABLE user_category_keywords (
    user_id      UUID        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    keyword      VARCHAR(40) NOT NULL,
    category_id  BIGINT      NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, keyword)
);

-- 4. Draft: pesan yang kategorinya belum bisa ditebak, menunggu user memilih lewat tombol
CREATE TABLE telegram_drafts (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            UUID          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    chat_id            BIGINT        NOT NULL,
    source_message_id  BIGINT        NOT NULL,
    type               VARCHAR(10)   NOT NULL,
    amount             NUMERIC(15,2) NOT NULL,
    note               VARCHAR(255),
    occurred_on        DATE          NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    expires_at         TIMESTAMPTZ   NOT NULL,
    CONSTRAINT chk_telegram_drafts_type CHECK (type IN ('EXPENSE', 'INCOME')),
    CONSTRAINT chk_telegram_drafts_amount CHECK (amount > 0),
    CONSTRAINT ux_telegram_drafts_message UNIQUE (chat_id, source_message_id)
);
CREATE INDEX ix_telegram_drafts_expires ON telegram_drafts (expires_at);

