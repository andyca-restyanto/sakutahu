CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL,
    name        VARCHAR(60)  NOT NULL,
    type        VARCHAR(10)  NOT NULL,
    kind        VARCHAR(10)  NOT NULL,
    color       VARCHAR(7)   NOT NULL,
    icon        VARCHAR(16)  NOT NULL,
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    -- NULL = kategori bawaan sistem; diisi jika kelak user boleh membuat kategori sendiri
    user_id     UUID REFERENCES users (id) ON DELETE CASCADE,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ux_categories_code UNIQUE (code),
    CONSTRAINT chk_categories_type CHECK (type IN ('EXPENSE', 'INCOME')),
    CONSTRAINT chk_categories_kind CHECK (
        (type = 'EXPENSE' AND kind IN ('SPENDING', 'SAVING')) OR (type = 'INCOME' AND kind = 'INCOME')
    ),
    CONSTRAINT chk_categories_color CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE transactions (
    id           UUID PRIMARY KEY,
    user_id      UUID          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type         VARCHAR(10)   NOT NULL,
    category_id  BIGINT        NOT NULL REFERENCES categories (id),
    amount       NUMERIC(15,2) NOT NULL,
    occurred_on  DATE          NOT NULL,
    note         VARCHAR(255),
    source       VARCHAR(10)   NOT NULL DEFAULT 'WEB',
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_transactions_type CHECK (type IN ('EXPENSE', 'INCOME')),
    CONSTRAINT chk_transactions_amount CHECK (amount > 0),
    CONSTRAINT chk_transactions_source CHECK (source IN ('WEB', 'TELEGRAM'))
);
CREATE INDEX ix_transactions_user_date ON transactions (user_id, occurred_on DESC);
CREATE INDEX ix_transactions_user_type_date ON transactions (user_id, type, occurred_on);

